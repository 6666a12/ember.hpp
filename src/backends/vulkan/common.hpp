// Frames in flight for the owned submission loop (WO-04); the skeleton keeps
// the constant so later stages share the value.
inline constexpr std::uint32_t kFramesInFlight = 2;
inline constexpr std::uint32_t kSimGroupSize = 64;
inline constexpr std::uint32_t kMaxSpawnRequests = maxSpawnRequests;
// Five public counters are copied back each frame (alive, deadHead, requests,
// capacity, allocated); the shader's counter block is eight words.
inline constexpr std::uint32_t kCounterWords = 8;
// Schedule storage holds metadata plus 512 three-word tiled sort commands
// (same bound as the GL backend: 2^30 capacity needs 276 commands).
inline constexpr std::uint64_t kScheduleBytes = (5 + 3 * 512) * sizeof(std::uint32_t);
// Event sub-emission (WO-08): GpuEvent is 48 B in std430; the queue is a
// 16-byte header followed by the fixed instance table.
inline constexpr std::uint32_t kMaxEventInstances = maxEventInstancesPerFrame;
inline constexpr std::uint32_t kMaxEventChildren = maxEventChildrenPerFrame;
inline constexpr std::uint64_t kGpuEventBytes = 48;
inline constexpr std::uint64_t kEventQueueBytes = 4ull * sizeof(std::uint32_t) + (std::uint64_t)kMaxEventInstances * kGpuEventBytes;
// Asynchronous statistics ring: one sample per update, bounded like the GL
// backend (4 slots; excess samples are dropped, never block simulation).
inline constexpr std::uint32_t kStatisticsSlots = 4;

