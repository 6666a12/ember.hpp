// Owned VkBuffer + VkDeviceMemory pair. No VMA: the backend allocates one
// memory object per resource, which is fine for the fixed resource set here.
struct Buffer {
    VkBuffer buffer = VK_NULL_HANDLE;
    VkDeviceMemory memory = VK_NULL_HANDLE;
    VkDeviceSize size = 0;
    void* mapped = nullptr; // non-null for persistently mapped host-visible
    bool valid() const { return buffer != VK_NULL_HANDLE; }
};

// Cached physical-device limits used by validateConfiguration.
